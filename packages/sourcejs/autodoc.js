"use strict";

const { DoesFileExist, EnsureDirectoryExists, WriteTextFile } = require("filesystem");
const { GetModule } = require("internal/runtime");

const g_strModuleName = "autodoc";
const g_strGeneratedDocumentationNotice = "Generated by SourceJS autodoc. Do not edit; regenerate instead.";
const g_AutomaticDocumentationRuntime = GetModule(g_strModuleName);

function NormalizePath(strPathValue) {
	return String(strPathValue).replace(/\\/g, "/").replace(/\/+/g, "/").replace(/\/$/, "");
}

function JoinPath(...vecPathParts) {
	const HasPathPart = (strPathPart) => {
		if ((strPathPart === null) || (strPathPart === undefined)) {
			return false;
		}

		return String(strPathPart) !== "";
	};

	const vecNonEmptyPathParts = vecPathParts.filter(HasPathPart);

	return NormalizePath(vecNonEmptyPathParts.join("/"));
}

function GetModuleFileName(strModuleName) {
	return `${String(strModuleName).replace(/[\\/]/g, ".")}.rst`;
}

function CreateTitle(strText, strCharacter = "=") {
	const strTitleText = String(strText);

	return `${strTitleText}\n${strCharacter.repeat(strTitleText.length)}\n`;
}

function EscapeRST(strText) {
	return String(strText).replace(/`/g, "\\`");
}

function EscapeHTML(strText) {
	return String(strText).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

class SphinxError extends Error {
	constructor(strMessage = "Unable to create, generate or build documentation.") {
		super(strMessage);
		this.name = "SphinxError";
	}
}

function WriteDocumentationFile(strDocumentationPath, strDocumentationText) {
	const strDocumentationDirectory = NormalizePath(strDocumentationPath).split("/").slice(0, -1).join("/");
	if (strDocumentationDirectory) {
		EnsureDirectoryExists(strDocumentationDirectory);
	}

	if (!WriteTextFile(strDocumentationPath, strDocumentationText)) {
		throw new SphinxError(`Unable to write documentation file: ${strDocumentationPath}`);
	}

	return strDocumentationPath;
}

function GetModuleNames() {
	return g_AutomaticDocumentationRuntime.GetModuleNames().slice().sort();
}

class SphinxProject {
	constructor(strPackageDirectory, strProjectDirectory) {
		this.m_strPackageDirectory = NormalizePath(strPackageDirectory);
		this.m_strProjectDirectory = NormalizePath(strProjectDirectory);

		this.ValidatePackage();
	}

	DoesProjectExist() {
		return DoesFileExist(this.m_strProjectDirectory);
	}

	DoesPackageExist() {
		return DoesFileExist(this.m_strPackageDirectory);
	}

	CreateProject(strAuthor, strProjectName = null, strVersion = "1") {
		if (this.DoesProjectExist()) {
			throw new SphinxError("The project already exists.");
		}

		this.ValidatePackage();
		EnsureDirectoryExists(this.m_strProjectDirectory);
		EnsureDirectoryExists(this.ProjectSourceDirectory);
		EnsureDirectoryExists(this.ProjectBuildDirectory);

		const strResolvedProjectName = strProjectName || this.m_strPackageDirectory.split("/").pop() || "SourceJS";
		const strConfigurationPath = JoinPath(this.ProjectSourceDirectory, "conf.py");
		const strConfigurationText = this.GetConfigurationText(strAuthor, strResolvedProjectName, strVersion);
		const strIndexPath = JoinPath(this.ProjectSourceDirectory, "index.rst");
		const strIndexText = this.GetIndexText(strResolvedProjectName);

		WriteDocumentationFile(strConfigurationPath, strConfigurationText);
		WriteDocumentationFile(strIndexPath, strIndexText);

		return true;
	}

	GenerateProjectFiles(strSubdirectory = "") {
		if (typeof strSubdirectory !== "string") {
			throw new TypeError("Documentation subdirectory must be a string.");
		}

		const strRelativeSubdirectory = strSubdirectory.replace(/\\/g, "/");
		if (strRelativeSubdirectory.startsWith("/") || /[:\0]/.test(strRelativeSubdirectory) || /(^|\/)\.\.[ .]*(\/|$)/.test(strRelativeSubdirectory)) {
			throw new SphinxError("Documentation subdirectory must be relative and contain no parent-directory components.");
		}

		this.ValidateProjectAndPackage();

		const strOutputDirectory = JoinPath(this.ProjectSourceDirectory, strRelativeSubdirectory);
		EnsureDirectoryExists(strOutputDirectory);

		const vecModuleNames = GetModuleNames();
		const strModulesIndexPath = JoinPath(strOutputDirectory, "modules.rst");
		const strModulesIndexText = this.GetModulesIndexText(vecModuleNames);
		WriteDocumentationFile(strModulesIndexPath, strModulesIndexText);

		for (const strModuleName of vecModuleNames) {
			const strModuleDocumentationPath = JoinPath(strOutputDirectory, GetModuleFileName(strModuleName));
			const strModuleDocumentationText = this.GetModuleText(strModuleName);
			WriteDocumentationFile(strModuleDocumentationPath, strModuleDocumentationText);
		}

		return vecModuleNames;
	}

	BuildProject(bClean = false) {
		if (typeof bClean !== "boolean") {
			throw new TypeError("bClean must be a boolean.");
		}

		this.ValidateProjectAndPackage();

		if (bClean) {
			EnsureDirectoryExists(this.ProjectBuildDirectory);
		}

		const vecModuleNames = GetModuleNames();
		const strIndexPath = JoinPath(this.ProjectBuildDirectory, "index.html");
		const strIndexText = this.GetHTMLIndexText(vecModuleNames);
		WriteDocumentationFile(strIndexPath, strIndexText);

		return strIndexPath;
	}

	RunQuickStart(strAuthor, strProjectName = null, strVersion = "1") {
		if (!this.DoesProjectExist()) {
			this.CreateProject(strAuthor, strProjectName, strVersion);
		}

		this.GenerateProjectFiles();

		return this.BuildProject();
	}

	ValidateProjectAndPackage() {
		this.ValidateProject();
		this.ValidatePackage();

		return true;
	}

	ValidateProject() {
		if (!this.DoesProjectExist()) {
			throw new SphinxError("Create the project before generating project files.");
		}

		return true;
	}

	ValidatePackage() {
		if (!this.DoesPackageExist()) {
			throw new SphinxError("The package does not exist.");
		}

		return true;
	}

	GetConfigurationText(strAuthor, strProjectName, strVersion) {
		return [
			`# ${g_strGeneratedDocumentationNotice}`,
			"",
			`project = ${JSON.stringify(String(strProjectName))}`,
			`author = ${JSON.stringify(String(strAuthor))}`,
			`version = ${JSON.stringify(String(strVersion))}`,
			"extensions = ['sphinx.ext.autodoc']",
			"source_suffix = '.rst'",
			"master_doc = 'index'",
			"",
		].join("\n");
	}

	GetIndexText(strProjectName) {
		return [
			`.. ${g_strGeneratedDocumentationNotice}`,
			"",
			CreateTitle(EscapeRST(strProjectName)),
			".. toctree::",
			"   :maxdepth: 2",
			"",
			"   modules",
			"",
		].join("\n");
	}

	GetModulesIndexText(vecModuleNames) {
		const vecDocumentationLines = [`.. ${g_strGeneratedDocumentationNotice}`, "", CreateTitle("SourceJS Modules"), ".. toctree::", "   :maxdepth: 1", ""];
		for (const strModuleName of vecModuleNames) {
			vecDocumentationLines.push(`   ${GetModuleFileName(strModuleName).replace(/\.rst$/, "")}`);
		}

		vecDocumentationLines.push("");

		return vecDocumentationLines.join("\n");
	}

	GetModuleText(strModuleName) {
		const strModuleHeading = EscapeRST(strModuleName);

		return [
			`.. ${g_strGeneratedDocumentationNotice}`,
			"",
			CreateTitle(strModuleHeading),
			`.. js:module:: ${strModuleHeading}`,
			"",
			"Runtime import:",
			"",
			".. code-block:: js",
			"",
			`   const g_SourceModule = require(${JSON.stringify(strModuleName)});`,
			"",
		].join("\n");
	}

	GetHTMLIndexText(vecModuleNames) {
		const CreateModuleListItem = (strModuleName) => `\t\t<li><code>${EscapeHTML(strModuleName)}</code></li>`;
		const strModuleListItems = vecModuleNames.map(CreateModuleListItem).join("\n");

		return [
			"<!doctype html>",
			`<!-- ${g_strGeneratedDocumentationNotice} -->`,
			"<html>",
			"<head>",
			"\t<meta charset=\"utf-8\">",
			"\t<title>SourceJS Modules</title>",
			"</head>",
			"<body>",
			"\t<h1>SourceJS Modules</h1>",
			"\t<ul>",
			strModuleListItems,
			"\t</ul>",
			"</body>",
			"</html>",
			"",
		].join("\n");
	}

	get ProjectSourceDirectory() {
		return JoinPath(this.m_strProjectDirectory, "source");
	}

	get ProjectBuildDirectory() {
		return JoinPath(this.m_strProjectDirectory, "build");
	}
}

module.exports = {
	MODULE_NAME: g_strModuleName,
	GetModuleNames: GetModuleNames,
	SphinxError: SphinxError,
	SphinxProject: SphinxProject,
};
