"use strict";

const { CORE_COMMAND } = require("core/command");
const { WriteDump } = require("core/dumps");
const { GetModule } = require("internal/runtime");

const g_strModuleName = "core/command/docs";
const g_strDefaultDocumentationFileName = "sourcejs-runtime-modules";

function GenerateModuleDocumentation(strFileName = g_strDefaultDocumentationFileName) {
	const vecDocumentationLines = ["<!-- Generated by core/command/docs.GenerateModuleDocumentation; regenerate this runtime-module export snapshot instead of editing it. -->", "# SourceJS Runtime Modules", ""];
	const CoreRuntime = GetModule("core");
	const vecRuntimeModuleNames = Array.from(CoreRuntime.GetModules()).map(String).sort();
	for (const strRuntimeModuleName of vecRuntimeModuleNames) {
		const vecRuntimeModuleAPINames = Object.keys(GetModule(strRuntimeModuleName)).sort();

		vecDocumentationLines.push(`## ${strRuntimeModuleName}`);
		vecDocumentationLines.push("");
		vecDocumentationLines.push(vecRuntimeModuleAPINames.join(", "));
		vecDocumentationLines.push("");
	}

	const strDocumentationPath = WriteDump(strFileName, vecDocumentationLines.join("\n"));
	CORE_COMMAND.LogCommandMessage(`Documentation written to ${strDocumentationPath}`);

	return strDocumentationPath;
}

CORE_COMMAND.RegisterCommand(["docs", "generate"], function GenerateModuleDocumentationCommand(CommandContext) {
	const [strRequestedDocumentationFileName] = CommandContext.CommandArguments;

	return GenerateModuleDocumentation(strRequestedDocumentationFileName || g_strDefaultDocumentationFileName);
}, { Description: "Generate runtime module API documentation." });

module.exports = { MODULE_NAME: g_strModuleName, GenerateModuleDocumentation };
