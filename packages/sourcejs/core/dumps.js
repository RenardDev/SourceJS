"use strict";

const { GetConCommandBaseRecords } = require("cvars");
const { GetModule } = require("internal/runtime");

const g_WindowsAbsolutePathPattern = /^[A-Za-z]:[\\/]/;
const g_strRuntimeDumpProvenance = "# Generated by core/dumps; regenerate this runtime snapshot instead of editing it.";

const g_DumpsRuntime = GetModule("core/dumps");
const g_CoreRuntime = GetModule("core");
const g_EntitiesRuntime = GetModule("entities");
const g_EntityClassesRuntime = GetModule("entities/classes");
const g_EntityDataMapsRuntime = GetModule("entities/datamaps");
const g_EntityPropertiesRuntime = GetModule("entities/props");
const g_StringTablesRuntime = GetModule("stringtables");
const g_WeaponsRuntime = GetModule("weapons");

// JSON.stringify requires the key position before the value in its replacer callback.
function SerializeDumpProperty(strPropertyName, PropertyValue) {
	return (typeof PropertyValue === "bigint") ? String(PropertyValue) : PropertyValue;
}

function FormatDumpValue(DumpValue) {
	if ((DumpValue === null) || (DumpValue === undefined)) {
		return String(DumpValue);
	}

	if (typeof DumpValue === "object") {
		if ("Name" in DumpValue) {
			return String(DumpValue.Name);
		}

		if ("ClassName" in DumpValue) {
			return String(DumpValue.ClassName);
		}

		return JSON.stringify(DumpValue, SerializeDumpProperty);
	}

	return String(DumpValue);
}

function DescribeDumpObject(DumpObject) {
	if ((DumpObject === null) || (DumpObject === undefined)) {
		return String(DumpObject);
	}

	if (typeof DumpObject !== "object") {
		return String(DumpObject);
	}

	const vecPropertyDescriptions = [];
	for (const [strPropertyName, PropertyValue] of Object.entries(DumpObject)) {
		if (typeof PropertyValue === "function") {
			continue;
		}

		vecPropertyDescriptions.push(`${strPropertyName}=${FormatDumpValue(PropertyValue)}`);
	}

	return vecPropertyDescriptions.join(" ");
}

function ResolveDumpPath(strDumpFileName) {
	if ((typeof strDumpFileName !== "string") || (strDumpFileName.length === 0)) {
		throw new TypeError("Dump file name must be a non-empty string.");
	}

	const strNormalizedDumpPath = strDumpFileName.replace(/\\/g, "/");
	const strDumpPathWithExtension = strNormalizedDumpPath.toLowerCase().endsWith(".txt") ? strNormalizedDumpPath : `${strNormalizedDumpPath}.txt`;
	if (strDumpPathWithExtension.startsWith("/") || g_WindowsAbsolutePathPattern.test(strDumpPathWithExtension)) {
		return strDumpPathWithExtension;
	}

	const strDumpRoot = g_DumpsRuntime.Root;
	if ((typeof strDumpRoot !== "string") || (strDumpRoot.length === 0)) {
		throw new Error("SourceJS dump root is unavailable.");
	}

	return `${strDumpRoot.replace(/\/+$/, "")}/${strDumpPathWithExtension.replace(/^\/+/, "")}`;
}

function WriteDump(strDumpFileName, DumpText) {
	const strDumpFilePath = ResolveDumpPath(strDumpFileName);
	const strDumpDirectoryPath = strDumpFilePath.slice(0, Math.max(strDumpFilePath.lastIndexOf("/"), strDumpFilePath.lastIndexOf("\\")));
	if (strDumpDirectoryPath.length > 0) {
		const bDumpDirectoryReady = g_DumpsRuntime.EnsureDirectoryExists(strDumpDirectoryPath);
		if (!bDumpDirectoryReady) {
			throw new Error(`Unable to create dump directory: ${strDumpDirectoryPath}`);
		}
	}

	const strRenderedDumpText = String(DumpText);
	const bDumpWritten = g_DumpsRuntime.WriteTextFile(strDumpFilePath, strRenderedDumpText);
	if (!bDumpWritten) {
		throw new Error(`Unable to write dump file: ${strDumpFilePath}`);
	}

	return strDumpFilePath;
}

function WriteRuntimeDump(strDumpFileName, strDumpText) {
	return WriteDump(strDumpFileName, `${g_strRuntimeDumpProvenance}\n${strDumpText}`);
}

function DumpConVars(strDumpFileName = "convars") {
	const CompareConVarEntries = (LeftConVarEntry, RightConVarEntry) => String(LeftConVarEntry.Name).localeCompare(String(RightConVarEntry.Name));
	const vecConVarEntries = GetConCommandBaseRecords().slice().sort(CompareConVarEntries);
	const unTotalConVarCount = vecConVarEntries.length;
	let unConsoleCommandCount = 0;
	const vecDumpLines = [];
	for (const ConVarEntry of vecConVarEntries) {
		const bConVarIsCommand = ConVarEntry.IsCommand;
		if (bConVarIsCommand) {
			unConsoleCommandCount += 1;
		}

		vecDumpLines.push(`${ConVarEntry.Name} - ${bConVarIsCommand ? "CMD" : "VAR"} - flags ${ConVarEntry.Flags}`);

		if (ConVarEntry.Help) {
			vecDumpLines.push(`\t${ConVarEntry.Help}`);
		}

		if (!bConVarIsCommand) {
			vecDumpLines.push(`\tvalue: ${ConVarEntry.Value}`);
			vecDumpLines.push(`\tdefault: ${ConVarEntry.DefaultValue}`);
		}

		vecDumpLines.push("");
	}

	const unConsoleVariableCount = unTotalConVarCount - unConsoleCommandCount;
	vecDumpLines.unshift(`Commands: ${unConsoleCommandCount} - Variables: ${unConsoleVariableCount} - Total: ${unTotalConVarCount}`, "");

	return WriteRuntimeDump(strDumpFileName, vecDumpLines.join("\n"));
}

function DumpServerClasses(strDumpFileName = "serverClasses") {
	const vecDumpLines = [];
	for (const ServerClass of g_EntityPropertiesRuntime.GetServerClasses()) {
		vecDumpLines.push(`${ServerClass.Name} -> ${ServerClass.Table.Name}`);

		for (const ServerProperty of g_EntityPropertiesRuntime.GetServerClassProperties(ServerClass)) {
			vecDumpLines.push(`    ${DescribeDumpObject(ServerProperty)}`);
		}

		vecDumpLines.push("");
	}

	return WriteRuntimeDump(strDumpFileName, vecDumpLines.join("\n"));
}

function DumpDataMaps(strDumpFileName = "datamaps") {
	const vecDumpLines = [];
	for (const strEntityClassName of g_EntityClassesRuntime.GetEntityClassNames()) {
		const EntityDataMap = g_EntityDataMapsRuntime.GetEntityDataMap(strEntityClassName);
		if (!EntityDataMap) {
			continue;
		}

		const BaseDataMap = EntityDataMap.BaseAddress ? g_EntityDataMapsRuntime.GetEntityDataMap(EntityDataMap.BaseAddress) : null;
		vecDumpLines.push(`${strEntityClassName} -> ${BaseDataMap?.ClassName ?? ""}`);

		for (const DataMapField of g_EntityDataMapsRuntime.GetEntityDataMapFields(EntityDataMap, true)) {
			vecDumpLines.push(`    ${DescribeDumpObject(DataMapField)}`);
		}

		vecDumpLines.push("");
	}

	return WriteRuntimeDump(strDumpFileName, vecDumpLines.join("\n"));
}

function DumpStringTables(strDumpFileName = "stringTables") {
	const vecDumpLines = [];
	for (const StringTable of g_StringTablesRuntime.GetAllStringTables()) {
		vecDumpLines.push(DescribeDumpObject(StringTable));
	}

	return WriteRuntimeDump(strDumpFileName, `${vecDumpLines.join("\n")}\n`);
}

function DumpWeaponScripts(strDumpFileName = "weaponScripts") {
	const vecDumpLines = ["Weapon names:"];
	for (const strWeaponName of g_WeaponsRuntime.GetNames()) {
		vecDumpLines.push(`    ${strWeaponName}`);
	}

	vecDumpLines.push("", "Weapon classes:");

	for (const strWeaponClassName of g_WeaponsRuntime.GetClasses()) {
		vecDumpLines.push(`    ${strWeaponClassName}`);
	}

	vecDumpLines.push("", "Live weapons:");

	for (const LiveWeapon of g_WeaponsRuntime.GetAllWeapons()) {
		vecDumpLines.push(`    ${DescribeDumpObject(LiveWeapon)}`);
	}

	return WriteRuntimeDump(strDumpFileName, `${vecDumpLines.join("\n")}\n`);
}

function DumpClassInfo(strDumpFileName = "classInfo") {
	const vecRuntimeModuleNames = Array.from(g_CoreRuntime.GetModules(), String).sort();
	const FormatRuntimeModuleLine = (strRuntimeModuleName) => {
		const vecRuntimeModuleMemberNames = Object.keys(GetModule(strRuntimeModuleName)).sort();

		return `${strRuntimeModuleName}: ${vecRuntimeModuleMemberNames.join(", ")}`;
	};

	const vecDumpLines = vecRuntimeModuleNames.map(FormatRuntimeModuleLine);

	return WriteRuntimeDump(strDumpFileName, `${vecDumpLines.join("\n")}\n`);
}

function DumpEntities(strDumpFileName = "entities") {
	const vecDumpLines = g_EntitiesRuntime.GetAllEntities().map(DescribeDumpObject);

	return WriteRuntimeDump(strDumpFileName, `${vecDumpLines.join("\n")}\n`);
}

module.exports = {
	DumpClassInfo,
	DumpConVars,
	DumpDataMaps,
	DumpEntities,
	DumpServerClasses,
	DumpStringTables,
	DumpWeaponScripts,
	ResolveDumpPath,
	WriteDump,
};
