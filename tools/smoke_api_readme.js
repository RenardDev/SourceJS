#!/usr/bin/env node

"use strict";

const g_Assert = require("node:assert/strict");
const g_FileSystem = require("node:fs");
const g_Path = require("node:path");
const g_VM = require("node:vm");

const g_strRepositoryRoot = g_Path.resolve(__dirname, "..");
const g_strPackageRoot = g_Path.join(g_strRepositoryRoot, "packages", "sourcejs");
const g_strDocumentationPath = g_Path.join(g_strRepositoryRoot, "docs", "api", "README.md");
const g_setNativeOnlyModules = new Set(["cpr", "redis", "soci", "socket"]);
const g_setOmittedPackageModules = new Set(["players/language/cache"]);
const g_vecModuleCalls = [];

function GetHeadingAnchor(strHeading) {
	return strHeading.toLowerCase().replace(/`/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function CollectModuleNames(strDirectoryPath, vecModuleNamesOut = []) {
	for (const Entry of g_FileSystem.readdirSync(strDirectoryPath, { withFileTypes: true })) {
		const strFilePath = g_Path.join(strDirectoryPath, Entry.name);
		if (Entry.isDirectory()) {
			CollectModuleNames(strFilePath, vecModuleNamesOut);
		} else if (Entry.name.endsWith(".js")) {
			vecModuleNamesOut.push(g_Path.relative(g_strPackageRoot, strFilePath).replace(/\\/g, "/").replace(/\.js$/, ""));
		}
	}

	return vecModuleNamesOut;
}

function VerifyContentsAnchors(strMarkdown) {
	const vecContents = strMarkdown.match(/## Contents\r?\n([\s\S]*?)\r?\n## Runtime Discovery/);
	g_Assert.ok(vecContents, "API index contents section");

	const vecDocumentedAnchors = [...vecContents[1].matchAll(/\]\(#([^)]+)\)/g)].map((vecMatch) => vecMatch[1]);
	const vecSectionAnchors = [...strMarkdown.matchAll(/^## (.+)$/gm)].map((vecMatch) => GetHeadingAnchor(vecMatch[1])).filter((strAnchor) => strAnchor !== "contents");
	g_Assert.deepEqual(vecDocumentedAnchors, vecSectionAnchors, "API index contents anchors");
}

const g_strDocumentation = g_FileSystem.readFileSync(g_strDocumentationPath, "utf8");
const g_vecCodeBlocks = [...g_strDocumentation.matchAll(/```js\r?\n([\s\S]*?)```/g)].map((vecMatch) => vecMatch[1]);
const g_vecModuleRows = [...g_strDocumentation.matchAll(/^\| `([^`]+)` \| \[[^\]]+\]\(([^)]+)\)/gm)].map((vecMatch) => ({
	ModuleName: vecMatch[1],
	Reference: vecMatch[2],
}));
const g_vecDocumentedNames = g_vecModuleRows.map((Row) => Row.ModuleName);
const g_vecDocumentedReferences = g_vecModuleRows.map((Row) => Row.Reference);
const g_vecPackageModuleNames = CollectModuleNames(g_strPackageRoot);
const g_vecExpectedPackageModules = g_vecPackageModuleNames.filter((strModuleName) => {
	if ((strModuleName === "index") || strModuleName.endsWith("/index") || strModuleName.endsWith("/impl") || g_setOmittedPackageModules.has(strModuleName) || strModuleName.startsWith("internal/")) {
		return false;
	}

	return !strModuleName.split("/").some((strPart) => strPart.startsWith("_"));
});

g_Assert.equal(g_vecCodeBlocks.length, 1, "API index runtime-discovery workflow count");
g_Assert.equal(new Set(g_vecDocumentedNames).size, g_vecDocumentedNames.length, "API index module names are unique");
g_Assert.equal(new Set(g_vecDocumentedReferences).size, g_vecDocumentedReferences.length, "API index references are unique");
g_Assert.deepEqual(g_vecDocumentedNames, g_vecDocumentedNames.slice().sort(), "API index module names are sorted");
g_Assert.ok(!g_strDocumentation.includes("Generated by"), "API index must be maintained by hand.");
g_Assert.ok(g_strDocumentation.includes("whole-module import is deliberate"), "API index must justify dynamic whole-module reflection.");
g_Assert.ok(!g_strDocumentation.includes("console."), "API index must not depend on console-only inspection.");
g_Assert.ok(!/[^\x00-\x7F]/.test(g_strDocumentation), "API index must remain valid ASCII.");

VerifyContentsAnchors(g_strDocumentation);

const g_strDocumentationWithoutCode = g_strDocumentation.replace(/```[\s\S]*?```/g, "");
const g_vecDocumentationLinks = [...g_strDocumentationWithoutCode.matchAll(/\[[^\]]+\]\(([^)]+)\)/g)].map((vecMatch) => vecMatch[1]);
for (const strTarget of g_vecDocumentationLinks) {
	if (strTarget.startsWith("#") || /^[a-z]+:/i.test(strTarget)) {
		continue;
	}

	const strTargetPath = g_Path.resolve(g_Path.dirname(g_strDocumentationPath), strTarget.split("#", 1)[0]);
	g_Assert.ok(g_FileSystem.existsSync(strTargetPath), `API index link must exist: ${strTarget}`);
}

for (const Row of g_vecModuleRows) {
	const strReferencePath = g_Path.resolve(g_Path.dirname(g_strDocumentationPath), Row.Reference.split("#", 1)[0]);
	g_Assert.ok(g_FileSystem.existsSync(strReferencePath), `API index reference must exist: ${Row.Reference}`);
}

for (const strModuleName of g_vecExpectedPackageModules) {
	g_Assert.ok(g_vecDocumentedNames.includes(strModuleName), `public package module missing from API index: ${strModuleName}`);
}

for (const strModuleName of g_vecDocumentedNames) {
	const bHasDirectoryIndex = g_vecPackageModuleNames.includes(`${strModuleName}/index`);
	g_Assert.ok(g_vecExpectedPackageModules.includes(strModuleName) || bHasDirectoryIndex || g_setNativeOnlyModules.has(strModuleName) || g_setOmittedPackageModules.has(strModuleName), `API index module has no package or native-only contract: ${strModuleName}`);
}

for (const strModuleName of g_setNativeOnlyModules) {
	g_Assert.ok(g_vecDocumentedNames.includes(strModuleName), `mandatory native-only module missing from API index: ${strModuleName}`);
}

const g_RuntimeModules = {
	autodoc: {
		GetModuleNames() {
			g_vecModuleCalls.push("modules");

			return ["core", "memory/hooks/entities"];
		},
	},
	core: {
		GetVersion() {
			return "0.3.0";
		},
	},
	"memory/hooks/entities": {
		Create() {},
		Remove() {},
	},
};

function RequireDocumentation(strModuleName) {
	if (!Object.hasOwn(g_RuntimeModules, strModuleName)) {
		throw new Error(`unexpected API index documentation module ${strModuleName}`);
	}

	return g_RuntimeModules[strModuleName];
}

const g_ModuleRecord = { exports: {} };
const g_Script = new g_VM.Script(`(function(require, module, exports) {\n${g_vecCodeBlocks[0]}\n})`, {
	filename: "docs/api/README.md:1",
});
const g_Callback = g_Script.runInThisContext();
g_Callback(RequireDocumentation, g_ModuleRecord, g_ModuleRecord.exports);

g_Assert.equal(g_vecModuleCalls.length, 0, "API index example must not enumerate runtime modules during block load.");
g_Assert.deepEqual(g_ModuleRecord.exports.InspectRuntimeModules(), [
	{
		ExportNames: ["GetVersion"],
		ModuleName: "core",
	},
	{
		ExportNames: ["Create", "Remove"],
		ModuleName: "memory/hooks/entities",
	},
], "documented runtime module reflection");
g_Assert.deepEqual(g_vecModuleCalls, ["modules"], "documented runtime discovery is explicit");

console.log("[smoke_api_readme] ok");
