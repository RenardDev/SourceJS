function LoadNetChannelModules(NativeNetChannel = g_NativeNetChannel) {
	const mapOriginalRegisteredTypes = new Map(g_mapRegisteredTypes);
	const Global = { sourcejs: { netchannel: NativeNetChannel } };
	require(g_strBitbuffersMockPath).InstallBitBuffersMock(Global);

	const mapModules = new Map();
	const Memory = {
		RegisterObjectType(strName, Constructor) {
			g_mapRegisteredTypes.set(strName, Constructor);
		},
	};

	const LoadModule = (strModulePath) => {
		if (mapModules.has(strModulePath)) {
			return mapModules.get(strModulePath).exports;
		}

		const CommonJSModule = { exports: {} };
		mapModules.set(strModulePath, CommonJSModule);

		try {
			g_VM.runInNewContext(g_FileSystem.readFileSync(strModulePath, "utf8"), {
				sourcejs: Global.sourcejs,
				exports: CommonJSModule.exports,
				module: CommonJSModule,

				require(strModuleName) {
					if (strModuleName === "internal/runtime") {
						return LoadModule(g_strRuntimePath);
					}

					if (strModuleName === "memory") {
						return Memory;
					}

					if (strModuleName === "bitbuffers") {
						return LoadModule(g_strBitbuffersPath);
					}

					throw new Error(`Unexpected package import: ${strModuleName}`);
				},
			}, { filename: strModulePath, timeout: g_unScriptTimeoutMilliseconds });
		} catch (CaughtError) {
			if (mapModules.get(strModulePath) === CommonJSModule) {
				mapModules.delete(strModulePath);
			}

			throw CaughtError;
		}

		return CommonJSModule.exports;
	};

	try {
		return { Bitbuffers: LoadModule(g_strBitbuffersPath), NetChannel: LoadModule(g_strNetChannelPath) };
	} catch (CaughtError) {
		g_mapRegisteredTypes.clear();
		for (const [strName, Constructor] of mapOriginalRegisteredTypes) {
			g_mapRegisteredTypes.set(strName, Constructor);
		}

		throw CaughtError;
	}
}

