	g_Assert.equal(Channel.MessageHandler.Address, g_unHandlerAddress);
	g_Assert.ok(Channel.SendNetChannelFile("download/demo.dat", 12));
	g_Assert.ok(Channel.DenyNetChannelFile("download/demo.dat", 13));
	g_Assert.equal(Channel.RequestNetChannelFile("download/demo.dat"), 7);
	g_Assert.ok(Channel.SendNetChannelData(new Uint8Array([0x01, 0x02]), false));

	const Message = NetChannel.NetMessage.CreateNetMessageFromAddress(g_unMessageAddress);
	const ReadBuffer = { Bytes: new Uint8Array([0xFF, 0x00]), DataBitCount: 16 };
	const WriteBuffer = { Bytes: new Uint8Array(0x02), MaximumBitCount: 16 };

	g_Assert.ok(Message.ProcessNetMessage());
	g_Assert.equal(Message.MessageType, 5);
	g_Assert.equal(Message.MessageGroup, 9);
	g_Assert.equal(Message.MessageName, "svc_SourceJS");

