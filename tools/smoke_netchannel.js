function CheckBitBufferWriteBack() {
	const unWrittenBitCount = 11;
	const NativeNetChannel = {
		...g_NativeNetChannel,

		WriteMessageToBuffer() {
			return { Succeeded: true, Bytes: new Uint8Array([0xAA, 0x55]), WrittenBitCount: unWrittenBitCount };
		},
	};
	const Modules = LoadNetChannelModules(NativeNetChannel);
	const Message = Modules.NetChannel.NetMessage.CreateNetMessageFromAddress(g_unMessageAddress);
	const Writer = new Modules.Bitbuffers.BitBufferWrite(0x02);
	g_Assert.equal(Writer.CurrentBit, 0);
	g_Assert.ok(Message.WriteNetMessageToBuffer(Writer));
	g_Assert.equal(Writer.CurrentBit, unWrittenBitCount);
	g_Assert.equal(Writer.WrittenBitCount, unWrittenBitCount);
	g_Assert.equal(Writer.WrittenByteCount, 2);
	g_Assert.deepEqual(Array.from(Writer.Bytes), [0xAA, 0x55]);
	g_Assert.equal(Object.hasOwn(Writer, "WrittenBitCount"), false, "write-back must use the writable position, not shadow its derived getter");
}

function CheckDataRateDocumentationCleanup() {
	const strMarkdown = g_FileSystem.readFileSync(g_strNetChannelDocumentationPath, "utf8");
	const vecRateExamples = ExtractJavaScriptBlocks(strMarkdown).filter((strSource) => strSource.includes("g_flRequestedNetChannelDataRate"));
	g_Assert.equal(vecRateExamples.length, 1, "one data-rate restoration example");

	const flPreviousRate = g_flDataRate;
	const unPreviousNativeCallCount = g_vecNativeCalls.length;

	for (const strMode of [
		"ADJUSTED",
		"OPERATIONTHROW",
		"CLEANUPFALSE",
		"CLEANUPTHROW",
		"BOTHTHROW",
		"NULLANDCLEANUPTHROW",
		"INVALIDREADBACK",
		"FRACTIONALREADBACK",
	]) {
		const OperationError = new Error("Controlled rate operation failure");
		const CleanupError = new Error("Controlled rate cleanup failure");
		let unSetCount = 0;
		const NativeNetChannel = {
			...g_NativeNetChannel,

			GetRequiredInformationFromAddress(unAddress) {
				const Information = g_NativeNetChannel.GetRequiredInformationFromAddress(unAddress);
				if (((strMode === "INVALIDREADBACK") || (strMode === "FRACTIONALREADBACK")) && (unSetCount === 1)) {
					Information.DataRate = (strMode === "FRACTIONALREADBACK") ? 30000.5 : NaN;
				}

				return Information;
			},

			SetDataRate(unAddress, flDataRate) {
				unSetCount += 1;
				if (unSetCount === 1) {
					if ((strMode === "OPERATIONTHROW") || (strMode === "BOTHTHROW")) {
						throw OperationError;
					}

					if (strMode === "NULLANDCLEANUPTHROW") {
						throw null;
					}

					// Simulate a permitted engine policy without claiming live SDK execution.
					return g_NativeNetChannel.SetDataRate(unAddress, (strMode === "ADJUSTED") ? (flDataRate - 1) : flDataRate);
				}

				g_Assert.equal(flDataRate, flPreviousRate, "restoration uses the captured rate");

				if (strMode === "CLEANUPFALSE") {
					return false;
				}

				if ((strMode === "CLEANUPTHROW") || (strMode === "BOTHTHROW") || (strMode === "NULLANDCLEANUPTHROW")) {
					throw CleanupError;
				}

				return g_NativeNetChannel.SetDataRate(unAddress, flDataRate);
			},
		};
		const Modules = LoadNetChannelModules(NativeNetChannel);

		const ExecuteExample = () => g_VM.runInNewContext(vecRateExamples[0], {
			require(strName) {
				g_Assert.equal(strName, "netchannel");

				return Modules.NetChannel;
			},
		}, { filename: `${g_strNetChannelDocumentationPath}:data-rate-${strMode}`, timeout: g_unScriptTimeoutMilliseconds });

		try {
			if (strMode === "ADJUSTED") {
				g_Assert.doesNotThrow(ExecuteExample, "the example accepts an engine-adjusted rate");
				g_Assert.equal(g_flDataRate, flPreviousRate, "the example restores the previous rate");

			} else {
				g_Assert.throws(ExecuteExample, (CaughtError) => {
					if ((strMode === "BOTHTHROW") || (strMode === "NULLANDCLEANUPTHROW")) {
						g_Assert.equal(CaughtError.name, "AggregateError", "both errors survive cleanup");
						g_Assert.equal(CaughtError.errors[0], (strMode === "BOTHTHROW") ? OperationError : null, "original thrown value survives");
						g_Assert.equal(CaughtError.errors[1], CleanupError, "cleanup error identity survives");

					} else if (strMode === "OPERATIONTHROW") {
						g_Assert.equal(CaughtError, OperationError, "operation error identity survives successful cleanup");

					} else if (strMode === "CLEANUPTHROW") {
						g_Assert.equal(CaughtError, CleanupError, "cleanup error identity survives");

					} else {
						g_Assert.match(CaughtError.message, (strMode === "CLEANUPFALSE") ? /could not restore/ : /invalid live rate/, "failed status/read-back is reported");
					}

					return true;
				}, strMode);
			}

			g_Assert.equal(unSetCount, 2, "every exit attempts restoration exactly once");
		} finally {
			g_flDataRate = flPreviousRate;
			g_vecNativeCalls.length = unPreviousNativeCallCount;
		}
	}
}

function CheckPartialNetMessageBufferUpdates() {
	let unWriteCallCount = 0;
	const NativeNetChannel = {
		...g_NativeNetChannel,

		ReadMessageFromBuffer() {
			return { Succeeded: false, ReadBitCount: 11 };
		},

		WriteMessageToBuffer() {
			unWriteCallCount += 1;

			return { Succeeded: false, Bytes: new Uint8Array([0xAA, 0x55]), WrittenBitCount: 11 };
		},
	};
	const Modules = LoadNetChannelModules(NativeNetChannel);
	const Message = Modules.NetChannel.NetMessage.CreateNetMessageFromAddress(g_unMessageAddress);
	const ReadBuffer = { Bytes: new Uint8Array(0x02), DataBitCount: 16, CurrentBit: 5 };
	g_Assert.equal(Message.ReadNetMessageFromBuffer(ReadBuffer), false, "failed native reads preserve the failed status");
	g_Assert.equal(ReadBuffer.CurrentBit, 11, "read-back replaces the cursor even after false, rather than advancing the old cursor");

	const Writer = new Modules.Bitbuffers.BitBufferWrite(0x02);
	g_Assert.equal(Message.WriteNetMessageToBuffer(Writer), false, "failed native writes preserve the failed status");
	g_Assert.equal(Writer.CurrentBit, 11, "failed native writes still update the writer cursor");
	g_Assert.equal(Writer.WrittenBitCount, 11, "failed native writes retain partial output length");
	g_Assert.deepEqual(Array.from(Writer.Bytes), [0xAA, 0x55], "failed native writes retain partial bytes");

	const arrRawBytes = new Uint8Array([0xFF, 0x00]);
	g_Assert.equal(Message.WriteNetMessageToBuffer(arrRawBytes), false, "raw byte storage returns the failed status");
	g_Assert.deepEqual(Array.from(arrRawBytes), [0xFF, 0x00], "the wrapper never copies output back into raw byte storage");

	const unPreviousWriteCallCount = unWriteCallCount;
	const FrozenBuffer = Object.freeze({ Bytes: new Uint8Array(0x02), MaximumBitCount: 16 });
	g_Assert.throws(() => Message.WriteNetMessageToBuffer(FrozenBuffer), { name: "TypeError" }, "read-only output fields reject write-back");
	g_Assert.equal(unWriteCallCount, unPreviousWriteCallCount + 1, "an output assignment error occurs after the native method ran");
}

function CheckNetMessageDocumentationBuffers() {
	const strMarkdown = g_FileSystem.readFileSync(g_strNetChannelDocumentationPath, "utf8");
	const vecReadExamples = ExtractJavaScriptBlocks(strMarkdown).filter((strSource) => strSource.includes("function ParseNetMessageFromBytesCallback("));
	g_Assert.equal(vecReadExamples.length, 1, "one binary message-read callback");

	const vecWriteExamples = ExtractJavaScriptBlocks(strMarkdown).filter((strSource) => strSource.includes("function SerializeNetMessageToBytesCallback("));
	g_Assert.equal(vecWriteExamples.length, 1, "one binary message-write callback");

	for (const bReadSucceeded of [true, false]) {
		let unReadCallCount = 0;
		const NativeNetChannel = {
			...g_NativeNetChannel,

			ReadMessageFromBuffer(unAddress, MessageBuffer) {
				g_Assert.equal(unAddress, g_unMessageAddress, "message address reaches the native endpoint");
				g_Assert.deepEqual(Array.from(MessageBuffer.Bytes), [0xFF, 0x00], "typed storage reaches native processing as two bytes, not comma-separated text");
				g_Assert.equal(MessageBuffer.DataBitCount, 16, "two bytes have sixteen valid bits");
				g_Assert.equal(MessageBuffer.CurrentBit, 0, "input reader begins at the start");
				unReadCallCount += 1;

				return { Succeeded: bReadSucceeded, ReadBitCount: 11 };
			},
		};
		const Modules = LoadNetChannelModules(NativeNetChannel);

		class DocumentationByteReader extends Modules.Bitbuffers.BitBufferRead {
			constructor(arrBytes) {
				g_Assert.ok(ArrayBuffer.isView(arrBytes) && (arrBytes.BYTES_PER_ELEMENT === 1), "the example preserves byte-view storage at reader construction");
				super(arrBytes);
			}
		}

		const CheckedBitbuffers = { ...Modules.Bitbuffers, BitBufferRead: DocumentationByteReader };
		const CommonJSModule = { exports: {} };
		g_VM.runInNewContext(vecReadExamples[0], {
			module: CommonJSModule,

			require(strName) {
				if (strName === "netchannel") {
					return Modules.NetChannel;
				}

				g_Assert.equal(strName, "bitbuffers");

				return CheckedBitbuffers;
			},
		}, { filename: `${g_strNetChannelDocumentationPath}:byte-reader-${bReadSucceeded}`, timeout: g_unScriptTimeoutMilliseconds });

		const vecInvalidSources = [
			[0xFF, 0x00],
			"255,0",
			new Uint16Array([0x00FF]),
			new DataView(new ArrayBuffer(0x02)),
			new ArrayBuffer(0x02),
			null,
		];
		for (const Source of vecInvalidSources) {
			g_Assert.throws(() => RunNetChannelDocumentationCallback(CommonJSModule.exports, [g_unMessageAddress, Source]), { name: "TypeError" }, "non-byte-view input fails before native processing");
		}

		g_Assert.equal(unReadCallCount, 0, "rejected inputs never process the native message");

		const vecValidSources = [new Uint8Array([0xFF, 0x00]), new Uint8ClampedArray([0xFF, 0x00]), new Int8Array([-0x01, 0x00])];
		for (const arrBytes of vecValidSources) {
			const Result = RunNetChannelDocumentationCallback(CommonJSModule.exports, [g_unMessageAddress, arrBytes]);
			g_Assert.equal(Result.ReadSucceeded, bReadSucceeded, "native success/failure status is preserved");
			g_Assert.equal(Result.CurrentBit, 11, "partial native progress is returned even after false");
		}

		g_Assert.equal(unReadCallCount, vecValidSources.length, "each accepted input processes exactly once");
	}

	for (const bWriteSucceeded of [true, false]) {
		let unWriteCallCount = 0;
		let RetainedWriter = null;
		const NativeNetChannel = {
			...g_NativeNetChannel,

			WriteMessageToBuffer(unAddress, MessageBuffer) {
				g_Assert.equal(unAddress, g_unMessageAddress);
				g_Assert.equal(MessageBuffer.MaximumBitCount, 32, "four-byte write capacity reaches the native endpoint");
				g_Assert.equal(MessageBuffer.CurrentBit, 0, "output begins at the start");
				RetainedWriter = MessageBuffer;
				unWriteCallCount += 1;

				return { Succeeded: bWriteSucceeded, Bytes: new Uint8Array([0xAA, 0x55, 0xCC, 0xDD]), WrittenBitCount: 11 };
			},
		};
		const Modules = LoadNetChannelModules(NativeNetChannel);
		const CommonJSModule = { exports: {} };
		g_VM.runInNewContext(vecWriteExamples[0], {
			module: CommonJSModule,

			require(strName) {
				if (strName === "netchannel") {
					return Modules.NetChannel;
				}

				g_Assert.equal(strName, "bitbuffers");

				return Modules.Bitbuffers;
			},
		}, { filename: `${g_strNetChannelDocumentationPath}:byte-writer-${bWriteSucceeded}`, timeout: g_unScriptTimeoutMilliseconds });

		const Result = RunNetChannelDocumentationCallback(CommonJSModule.exports, [g_unMessageAddress, 0x04]);
		g_Assert.equal(Result.WriteSucceeded, bWriteSucceeded, "partial native writes preserve success/failure");
		g_Assert.equal(Result.WrittenBitCount, 11, "partial bit count is returned even after false");
		g_Assert.deepEqual(Array.from(Result.Bytes), [0xAA, 0x55], "output excludes unwritten byte capacity");
		g_Assert.equal(unWriteCallCount, 1, "serialization never retries native processing");

		Result.Bytes[0] = 0x00;
		g_Assert.equal(RetainedWriter.Bytes[0], 0xAA, "returned byte slice is not the writer's mutable storage");
	}
}

function CheckWorldNetworkSnapshots(NetChannelAPI) {
	const strExamplePath = g_Path.join(g_strRepositoryRootPath, "examples", "plugins", "disabled", "api-world-objects", "index.js");
	const strExample = g_FileSystem.readFileSync(strExamplePath, "utf8").replace(/\r\n/g, "\n");
	const nExampleStart = strExample.indexOf('\tLogResult("memory.MakeObject NetChannel",');
	const nExampleEnd = strExample.indexOf("\n}\n\nfunction IsInt32(", nExampleStart);
	g_Assert.ok((nExampleStart >= 0) && (nExampleEnd > nExampleStart), "world network snapshot callbacks must remain available");

	const vecProfiles = [
		[],
		[{ Connected: false, FakeClient: false, Index: 1 }, { Connected: true, FakeClient: true, Index: 3 }],
		[{ Connected: true, FakeClient: false, Index: 4 }],
		[{ Connected: true, FakeClient: false, Index: 1 }],
	];
	for (const vecPlayers of vecProfiles) {
		const mapResults = new Map();
		g_VM.runInNewContext(strExample.slice(nExampleStart, nExampleEnd), {
			...NetChannelAPI,
			GetAllPlayers: () => vecPlayers,
			LogResult: (strLabel, Callback) => mapResults.set(strLabel, Callback()),
			MakeObject: (Constructor, unAddress) => Constructor.CreateFromAddress(unAddress),
		}, { filename: strExamplePath, timeout: g_unScriptTimeoutMilliseconds });
		g_Assert.equal(mapResults.size, 3);

		const Wrapped = mapResults.get("memory.MakeObject NetChannel");
		const Metrics = mapResults.get("netchannel.info realtime metrics");
		const Channel = mapResults.get("netchannel.channel live object");
		const Human = vecPlayers.find((Player) => Player.Connected && !Player.FakeClient) ?? null;
		if (Human === null) {
			g_Assert.equal(Wrapped, null);
			g_Assert.equal(Metrics, null);
			g_Assert.equal(Channel, null);
			continue;
		}

		g_Assert.equal(Metrics.PlayerIndex, Human.Index);
		g_Assert.equal(Channel.PlayerIndex, Human.Index);

		if (Human.Index !== 1) {
			g_Assert.equal(Wrapped, null);
			g_Assert.equal(Metrics.Available, false);
			g_Assert.equal(Channel.Available, false);
			continue;
		}

		g_Assert.equal(Wrapped.AddressesMatch, true);
		g_Assert.equal(Wrapped.WrappedAddress, g_unChannelAddress);
		g_Assert.equal(Metrics.Address, g_unInformationAddress);
		g_Assert.equal(Metrics.Incoming.Latency, 0.15);
		g_Assert.equal(Metrics.Outgoing.Latency, 0.25);
		g_Assert.equal(Channel.MessageHandlerAddress, g_unHandlerAddress);
	}
}

