function ExtractJavaScriptBlocks(strMarkdown) {
	return [...strMarkdown.matchAll(/```js\r?\n([\s\S]*?)\r?\n```/g)].map((vecMatch) => vecMatch[1]);
}

function RunNetChannelDocumentationCallback(Callback, vecArguments) {
	// Bound synchronous callback bodies, not native IO or untrusted-code capabilities.
	const Script = new g_VM.Script("Callback(...Arguments)", { filename: `${g_strNetChannelDocumentationPath}:${Callback.name}` });

	return Script.runInNewContext({ Callback, Arguments: vecArguments }, { timeout: g_unScriptTimeoutMilliseconds });
}

function VerifyDocumentationCallback(Callback) {
	switch (Callback.name) {
		case "InspectNetMessageCallback": {
			const Result = RunNetChannelDocumentationCallback(Callback, [g_unMessageAddress]);
			g_Assert.equal(Result.MessageAddress, g_unMessageAddress);
			g_Assert.equal(Result.MessageName, "svc_SourceJS");
			g_Assert.equal(Result.MessageType, 5);
			g_Assert.equal(Result.MessageGroup, 9);
			g_Assert.equal(Result.ReliableDelivery, g_bReliableDelivery);
			g_Assert.equal(Result.NetChannelAddress, g_unMessageChannelAddress);
			g_Assert.equal(Result.DiagnosticText, "svc_SourceJS reliable");
			break;
		}

		case "RouteUnreliableNetMessageCallback": {
			const bPreviousReliableDelivery = g_bReliableDelivery;
			const unPreviousMessageChannelAddress = g_unMessageChannelAddress;

			try {
				g_Assert.equal(RunNetChannelDocumentationCallback(Callback, [g_unMessageAddress, 1]), true);
				g_Assert.equal(g_bReliableDelivery, false);
				g_Assert.equal(g_unMessageChannelAddress, g_unChannelAddress);
				g_Assert.equal(RunNetChannelDocumentationCallback(Callback, [g_unMessageAddress, 2]), false);
			} finally {
				g_bReliableDelivery = bPreviousReliableDelivery;
				g_unMessageChannelAddress = unPreviousMessageChannelAddress;
			}

			break;
		}

		case "ParseNetMessageFromBytesCallback": {
			const Result = RunNetChannelDocumentationCallback(Callback, [g_unMessageAddress, new Uint8Array([0xFF, 0x00])]);
			g_Assert.equal(Result.ReadSucceeded, true);
			g_Assert.equal(Result.CurrentBit, 11);
			break;
		}

		case "SerializeNetMessageToBytesCallback": {
			const Result = RunNetChannelDocumentationCallback(Callback, [g_unMessageAddress, 0x02]);
			g_Assert.equal(Result.WriteSucceeded, true);
			g_Assert.equal(Result.WrittenBitCount, 16);
			g_Assert.deepEqual(Array.from(Result.Bytes), [0xAA, 0x55]);
			break;
		}

		case "ProcessNetMessageCallback":
			g_Assert.equal(RunNetChannelDocumentationCallback(Callback, [g_unMessageAddress]), true);
			break;

		default:
			throw new Error(`Unexpected documentation callback: ${Callback.name}`);
	}
}

function VerifyDocumentation(NetChannel, Bitbuffers) {
	const strMarkdown = g_FileSystem.readFileSync(g_strNetChannelDocumentationPath, "utf8");
	const vecExamples = ExtractJavaScriptBlocks(strMarkdown);
	g_Assert.doesNotMatch(strMarkdown, /Generated by|generate_api_docs|console\./, "documentation contract");
	g_Assert.equal(vecExamples.length, g_unDocumentationExampleCount, "documentation JavaScript block count");

	for (const vecExampleEntry of vecExamples.entries()) {
		const unExampleIndex = vecExampleEntry[0];
		const strSource = vecExampleEntry[1];
		const CommonJSModule = { exports: {} };
		g_VM.runInNewContext(strSource, {
			exports: CommonJSModule.exports,
			module: CommonJSModule,

			require(strModuleName) {
				if (strModuleName === "netchannel") {
					return NetChannel;
				}

				if (strModuleName === "bitbuffers") {
					return Bitbuffers;
				}

				throw new Error(`Unexpected documentation import: ${strModuleName}`);
			},
		}, { filename: `${g_strNetChannelDocumentationPath}:example-${unExampleIndex + 1}`, timeout: g_unScriptTimeoutMilliseconds });

		if (unExampleIndex >= g_unFirstCallbackExampleIndex) {
			g_Assert.equal(typeof CommonJSModule.exports, "function", `documentation callback ${unExampleIndex + 1}`);
			VerifyDocumentationCallback(CommonJSModule.exports);
		}
	}
}

